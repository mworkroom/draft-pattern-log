test('read-only selection preserves a new draft and explicit Edit protects unsaved changes', async ({ page }) => {
  await seed(page)
  await page.locator('#student-name').fill('Unsaved new record')
  await page.locator('#short-notes').fill('Keep this draft.')
  const before = await page.evaluate(() => localStorage.getItem('sop-score-tracker:records:v1'))
  await page.getByRole('button', { name: 'Pattern Explorer', exact: true }).click()
  const explorer = page.getByRole('region', { name: 'Pattern Explorer', exact: true })
  const mina = explorer.locator('.matching-reviews-table tbody tr').filter({ hasText: 'Mina' }).filter({ hasText: '1차' })
  await mina.getByRole('button', { name: 'Mina', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Review Details' })).toBeVisible()
  await expect(page.locator('#student-name')).toHaveValue('Mina')
  await expect(page.locator('#student-name')).toBeDisabled()
  await expect(page.locator('#short-notes')).toHaveValue('Connect the experience and motivation.')
  await expect(page.getByRole('group', { name: 'Logic Connection', exact: true }).getByRole('button', { name: '0', exact: true })).toHaveAttribute('aria-pressed', 'true')
  expect(await page.evaluate(() => localStorage.getItem('sop-score-tracker:records:v1'))).toBe(before)
  page.once('dialog', dialog => dialog.dismiss())
  await page.getByRole('button', { name: 'Edit Review', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Review Details' })).toBeVisible()
  await page.getByRole('button', { name: 'Back to input' }).click()
  await expect(page.locator('#student-name')).toHaveValue('Unsaved new record')
  await expect(page.locator('#short-notes')).toHaveValue('Keep this draft.')
  await mina.getByRole('button', { name: 'Mina', exact: true }).click()
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: 'Edit Review', exact: true }).click()
  await expect(page.locator('#student-name')).toBeEnabled()
  await expect(page.locator('#student-name')).toBeFocused()
  await page.locator('#short-notes').fill('Updated evidence notes.')
  await explorer.locator('.matching-reviews-table').getByRole('button', { name: 'Genre', exact: true }).click()
  await expect(page.locator('#pattern-note')).toHaveValue('Repeated prompts.')
  await expect(page.getByRole('group', { name: 'Type 6 subtypes' }).locator('input:checked')).toHaveCount(2)
  await page.getByRole('button', { name: 'Back to input' }).click()
  await expect(page.locator('#short-notes')).toHaveValue('Updated evidence notes.')
  await page.getByRole('button', { name: 'Update Review', exact: true }).click()
  const stored = await page.evaluate(() => JSON.parse(localStorage.getItem('sop-score-tracker:records:v1')!).records)
  expect(stored).toHaveLength(records.length)
  expect(stored.find((record: ReviewRecordV1) => record.id === 'mina-1').notes).toBe('Updated evidence notes.')
  expect(Object.keys(stored[0]).sort()).toEqual(Object.keys(records[0]).sort())
})

test('a date-only draft change is protected and deleting a viewed record returns to the draft', async ({ page }) => {
  await seed(page)
  const initialDate = await page.locator('#review-date').inputValue()
  await page.locator('#review-date').fill('2026-09-01')
  let dialogs = 0
  const dismiss = async (dialog: import('@playwright/test').Dialog) => { dialogs++; await dialog.dismiss() }
  page.on('dialog', dismiss)
  await page.locator('.reviews-table').getByRole('button', { name: 'Edit Jun', exact: true }).click()
  expect(dialogs).toBe(1)
  await expect(page.locator('#student-name')).toHaveValue('')
  await page.locator('#review-date').fill(initialDate)
  await page.locator('.reviews-table').getByRole('button', { name: 'Edit Jun', exact: true }).click()
  await expect(page.locator('#student-name')).toHaveValue('Jun')
  expect(dialogs).toBe(1)
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.locator('#student-name').fill('Preserved draft')
  await page.locator('.reviews-table').getByRole('button', { name: 'Genre', exact: true }).click()
  page.off('dialog', dismiss)
  page.once('dialog', dialog => dialog.accept())
  await page.locator('.reviews-table').getByRole('button', { name: 'Delete Genre', exact: true }).click()
  await expect(page.locator('#student-name')).toHaveValue('Preserved draft')
  await expect(page.getByRole('button', { name: 'Save Review', exact: true })).toBeVisible()
})

