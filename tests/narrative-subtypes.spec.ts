import { expect, test } from '@playwright/test'
import { editSelectedReview, showStatistics } from './ui'

for (const width of [1280, 2048]) {
  test(`Type 4 subtypes preserve legacy records and Type 6 independently at ${width}px`, async ({ page }) => {
    const errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
    await page.setViewportSize({ width, height: width === 1280 ? 900 : 1152 })
    await page.goto('./')
    await expect(page).toHaveTitle('SOP Score Tracker')
    const form = page.getByRole('region', { name: 'Review editor' })
    const type4 = form.locator('.type-choice').filter({ hasText: 'Type 4 — Narrative / Indirect' })
    const narrative = form.getByRole('group', { name: 'Type 4 subtypes', exact: true })
    const genre = form.getByRole('group', { name: 'Type 6 subtypes', exact: true })
    await expect(narrative).toHaveCount(0)
    await type4.click()
    await expect(type4.locator('small')).toHaveText('핵심 내용을 직접 전달하기보다 서사적 전개나 간접적인 연결에 의존하여 단락의 역할과 논리적 흐름이 불명확해짐')
    await expect(narrative.locator('.type-choice strong')).toHaveText(['Delayed-Point Narrative', 'Question-Driven Narrative'])
    await expect(narrative.locator('.type-choice small')).toHaveText([
      '경험이나 상황을 먼저 서술하고 핵심 의미를 단락 후반이나 다음 단락에서 뒤늦게 설명함',
      '경험에서 배운 점이나 발전시킨 역량보다 새로운 질문의 생성과 확장을 반복적으로 강조하고, 질문을 단락 간 연결 장치로 사용함',
    ])
    await page.locator('#student-name').fill('Narrative Both')
    for (const row of await form.locator('.score-row').all()) await row.getByRole('button', { name: '1', exact: true }).click()
    await page.getByRole('button', { name: 'Save Review', exact: true }).click()
    await expect(page.getByRole('alert')).toContainText('Type 4')
    await narrative.getByRole('checkbox').nth(0).check()
    await narrative.getByRole('checkbox').nth(1).check()
    await expect(narrative.getByRole('checkbox', { checked: true })).toHaveCount(2)
    expect(await narrative.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
    expect(await narrative.locator('strong').first().evaluate(element => Number.parseFloat(getComputedStyle(element).fontSize))).toBeGreaterThanOrEqual(14)
    await form.locator('.type-choice').filter({ hasText: 'Type 6 — Genre Mismatch' }).click()
    for (const checkbox of await genre.getByRole('checkbox').all()) await checkbox.check()
    await expect(genre.getByRole('checkbox', { checked: true })).toHaveCount(2)
    await narrative.scrollIntoViewIfNeeded()
    if (process.env.NARRATIVE_QA_DIR) await page.screenshot({ path: `${process.env.NARRATIVE_QA_DIR}/narrative-subtypes-${width}.png` })
    await page.getByRole('button', { name: 'Save Review', exact: true }).click()
    await page.evaluate(() => {
      const key = 'sop-score-tracker:records:v1'
      const backup = JSON.parse(localStorage.getItem(key)!)
      const original = backup.records[0]
      const legacy = { ...original, id: 'legacy-narrative', studentName: 'Legacy Narrative', problemTypes: ['type4'], genreMismatchSubtypes: [] }
      delete legacy.narrativeSubtypes
      backup.records.push(legacy, { ...original, id: 'other-type', studentName: 'Other Type', problemTypes: ['type3'], genreMismatchSubtypes: [], narrativeSubtypes: [] })
      localStorage.setItem(key, JSON.stringify(backup))
    })
    await page.reload()
    await expect(page.locator('.storage-alert')).toHaveCount(0)
    await page.getByRole('button', { name: 'Legacy Narrative', exact: true }).click()
    await expect(narrative.getByRole('checkbox', { checked: true })).toHaveCount(0)
    await expect(narrative).toContainText('Not specified')
    await expect(narrative.getByRole('checkbox').first()).toBeDisabled()
    await page.getByRole('button', { name: 'Back to input', exact: true }).click()
    await showStatistics(page, 'Problem patterns')
    const statistics = page.getByRole('region', { name: 'Statistics', exact: true })
    const bars = statistics.getByRole('region', { name: 'Narrative / Indirect subtypes', exact: true })
    await expect(bars).toContainText('2 Type 4 reviews')
    await expect(bars.getByRole('progressbar', { name: 'Delayed-Point Narrative', exact: true })).toHaveAttribute('aria-valuenow', '1')
    await expect(bars.getByRole('progressbar', { name: 'Question-Driven Narrative', exact: true })).toHaveAttribute('aria-valuenow', '1')
    await expect(bars.getByRole('progressbar', { name: 'Not specified (Type 4)', exact: true })).toHaveAttribute('aria-valuenow', '1')
    await statistics.getByRole('button', { name: /^Filters/ }).click()
    const filter = statistics.getByRole('combobox', { name: 'Narrative / Indirect subtype', exact: true })
    await filter.selectOption('questionDrivenNarrative')
    await expect(bars).toContainText('1 Type 4 reviews')
    await filter.selectOption('__missing')
    await expect(bars.getByRole('progressbar', { name: 'Not specified (Type 4)', exact: true })).toHaveAttribute('aria-valuenow', '1')
    await statistics.getByRole('button', { name: 'Clear all', exact: true }).click()
    await page.getByRole('button', { name: 'Pattern Explorer', exact: true }).click()
    const explorer = page.getByRole('region', { name: 'Pattern Explorer', exact: true })
    const explorerFilter = explorer.getByRole('combobox', { name: 'Explorer Narrative / Indirect subtype', exact: true })
    await explorerFilter.selectOption('delayedPointNarrative')
    await expect(explorer.locator('.student-link')).toHaveText(['Narrative Both'])
    await explorerFilter.selectOption('__missing')
    await expect(explorer.locator('.student-link')).toHaveText(['Legacy Narrative'])
    await explorer.getByRole('button', { name: 'Clear', exact: true }).click()
    await expect(explorer.locator('.student-link')).toHaveCount(3)
    await page.getByRole('button', { name: 'Review Overview', exact: true }).click()
    await page.getByRole('button', { name: 'Narrative Both', exact: true }).click()
    await editSelectedReview(page)
    await expect(narrative.getByRole('checkbox', { checked: true })).toHaveCount(2)
    await expect(genre.getByRole('checkbox', { checked: true })).toHaveCount(2)
    await type4.click()
    await expect(narrative).toHaveCount(0)
    await expect(genre.getByRole('checkbox', { checked: true })).toHaveCount(2)
    await page.getByRole('button', { name: 'Update Review', exact: true }).click()
    await page.reload()
    const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('sop-score-tracker:records:v1')!).records)
    const current = saved.find((record: { studentName: string }) => record.studentName === 'Narrative Both')
    expect(current.narrativeSubtypes).toEqual([])
    expect(current.genreMismatchSubtypes).toEqual(['researchProposal', 'promptResponse'])
    const old = saved.find((record: { id: string }) => record.id === 'legacy-narrative')
    expect(old.problemTypes).toEqual(['type4'])
    expect(old.narrativeSubtypes).toEqual([])
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await expect(page.locator('vite-error-overlay')).toHaveCount(0)
    expect(errors).toEqual([])
  })
}
